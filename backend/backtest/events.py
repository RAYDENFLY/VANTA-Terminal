"""
VANTA Terminal — Event Definitions for Backtest State Machine
=============================================================
Defines immutable, strongly-typed discrete events for the bar event loop:
BarEvent -> SignalEvent -> OrderEvent -> FillEvent -> FundingEvent.
"""

from dataclasses import dataclass
from typing import Optional, Dict, Any
from backend.backtest.schemas import OrderType, OrderSide, PositionSide, ExitReason


@dataclass(frozen=True)
class BarEvent:
    """Represents a completed historical candle bar consumed by the engine."""
    timestamp_ms: int
    open: float
    high: float
    low: float
    close: float
    volume: float
    close_time_ms: int
    bar_index: int


@dataclass(frozen=True)
class SignalEvent:
    """
    Generated by a strategy upon bar $t$ close.
    Becomes actionable strictly at bar $t+1$ open (zero lookahead).
    """
    timestamp_ms: int
    symbol: str
    direction: PositionSide      # LONG, SHORT, FLAT
    order_type: OrderType = OrderType.MARKET
    limit_price: Optional[float] = None
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    time_expiry_bars: Optional[int] = None
    tag: str = "SIGNAL"


@dataclass(frozen=True)
class OrderEvent:
    """Order submitted for execution simulation."""
    order_id: int
    timestamp_ms: int
    symbol: str
    side: OrderSide              # BUY or SELL
    order_type: OrderType
    quantity: float
    price: Optional[float] = None
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    expiry_bar_index: Optional[int] = None
    reason: str = "SIGNAL_ENTRY"


@dataclass(frozen=True)
class FillEvent:
    """Result of an order execution fill."""
    order_id: int
    timestamp_ms: int
    symbol: str
    side: OrderSide
    fill_price: float
    quantity: float
    fee: float
    slippage_cost: float
    is_maker: bool = False
    exit_reason: Optional[ExitReason] = None
    is_ambiguous: bool = False


@dataclass(frozen=True)
class FundingEvent:
    """Settlement timestamp 8-hour funding debit or credit."""
    timestamp_ms: int
    symbol: str
    rate: float
    notional: float
    payment: float               # Positive = received (credit), Negative = paid (debit)
    position_side: PositionSide
