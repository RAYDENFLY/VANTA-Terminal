class MetaRejectionReason(str, Enum):
    BELOW_PROBABILITY_THRESHOLD = "BELOW_PROBABILITY_THRESHOLD"
    COOLDOWN_ACTIVE = "COOLDOWN_ACTIVE"
    INVALID_FEATURES = "INVALID_FEATURES"
    UNAVAILABLE_PREDICTION = "UNAVAILABLE_PREDICTION"


@dataclass
class MetaRejectionRecord:
    timestamp_ms: int
    symbol: str
    direction: PositionSide
    predicted_prob: float
    threshold: float
    reason: MetaRejectionReason
    details: str = ""


class MetaStrategyFilter(BaseStrategy):
    """
    Wraps an underlying primary strategy (STRAT-B-01) with a secondary meta-model
    classification gate and optional inter-trade cooldown.
    """

    def __init__(
        self,
        symbol: str,
        primary_strategy: BaseStrategy,
        policy_config: MetaPolicyConfig,
        meta_model: Optional[BaseMetaModel] = None,
        feature_lookup: Optional[Dict[int, np.ndarray]] = None
    ):
        self.symbol = symbol
        self.primary_strategy = primary_strategy
        self.policy_config = policy_config
        self.meta_model = meta_model
        self.feature_lookup = feature_lookup or {}

        # Tracking state
        self.last_exit_time_ms: Optional[int] = None
        self.rejection_records: List[MetaRejectionRecord] = []
        self.accepted_candidates_count: int = 0
        self.rejected_candidates_count: int = 0

    def notify_trade_exit(self, exit_time_ms: int) -> None:
        """Called by the portfolio engine or runner when an open position closes."""
        self.last_exit_time_ms = exit_time_ms

    def on_bar(self, bar: BarEvent, position: PositionTracker) -> Optional[SignalEvent]:
        """
        Executes streaming bar evaluation with causal meta-model gating.
        """
        # If position closed between bars, update exit time tracking
        if not position.is_open() and position.entry_time_ms > 0:
            pass

        # 1. Evaluate primary strategy
        primary_sig = self.primary_strategy.on_bar(bar, position)
        if primary_sig is None:
            return None

        # 2. Dynamic exit signals (e.g. Midline exit) bypass the entry filter
        if primary_sig.direction == PositionSide.FLAT:
            return primary_sig

        # 3. Candidate entry signal emitted: LONG or SHORT
        # Primary direction is strictly preserved
        candidate_dir = primary_sig.direction

        # A. Check Cooldown Lockout
        if self.policy_config.cooldown_bars > 0 and self.last_exit_time_ms is not None:
            cooldown_ms = self.policy_config.cooldown_bars * 3600 * 1000
            elapsed_since_exit = bar.timestamp_ms - self.last_exit_time_ms
            if elapsed_since_exit < cooldown_ms:
                self.rejected_candidates_count += 1
                self.rejection_records.append(MetaRejectionRecord(
                    timestamp_ms=bar.timestamp_ms,
                    symbol=self.symbol,
                    direction=candidate_dir,
                    predicted_prob=0.0,
                    threshold=self.policy_config.tau,
                    reason=MetaRejectionReason.COOLDOWN_ACTIVE,
                    details=f"Cooldown active: {elapsed_since_exit / 3600000:.2f}h < {self.policy_config.cooldown_bars}h"
                ))
                return None

        # B. If no meta-model attached, run unfiltered (Benchmark-0 baseline mode)
        if self.meta_model is None:
            self.accepted_candidates_count += 1
            return primary_sig

        # C. Feature Retrieval and Validation
        feat_vec = self.feature_lookup.get(bar.timestamp_ms)
        if feat_vec is None or len(feat_vec) != 21 or np.isnan(feat_vec).any():
            self.rejected_candidates_count += 1
            self.rejection_records.append(MetaRejectionRecord(
                timestamp_ms=bar.timestamp_ms,
                symbol=self.symbol,
                direction=candidate_dir,
                predicted_prob=0.0,
                threshold=self.policy_config.tau,
                reason=MetaRejectionReason.INVALID_FEATURES,
                details="Missing, incomplete, or NaN feature vector at signal timestamp."
            ))
            return None

        # D. Predict Meta-Model Probability
        feat_matrix = feat_vec.reshape(1, -1)
        prob_pos = float(self.meta_model.predict_proba_positive(feat_matrix)[0])

        # E. Apply Decision Hurdle tau
        if prob_pos < self.policy_config.tau:
            self.rejected_candidates_count += 1
            self.rejection_records.append(MetaRejectionRecord(
                timestamp_ms=bar.timestamp_ms,
                symbol=self.symbol,
                direction=candidate_dir,
                predicted_prob=round(prob_pos, 4),
                threshold=self.policy_config.tau,
                reason=MetaRejectionReason.BELOW_PROBABILITY_THRESHOLD,
                details=f"Confidence {prob_pos:.4f} below threshold {self.policy_config.tau:.4f}"
            ))
            return None

        # F. Candidate Accepted: Emit identical primary signal with metadata tag
        self.accepted_candidates_count += 1
        return SignalEvent(
            timestamp_ms=primary_sig.timestamp_ms,
            symbol=primary_sig.symbol,
            direction=primary_sig.direction,
            stop_loss=primary_sig.stop_loss,
            take_profit=primary_sig.take_profit,
            time_expiry_bars=primary_sig.time_expiry_bars,
            tag=f"{primary_sig.tag}_META_ACCEPT_{prob_pos:.4f}"
        )
