"""
VANTA Terminal — Meta-Strategy Execution Wrapper (Phase 5D.1)
=============================================================
Implements the secondary meta-classification execution filter wrapping the frozen
STRAT-B-01 Donchian Breakout 1H primary strategy.

Key Invariants:
1. Strict Direction Preservation: Candidate signals are evaluated strictly in their
   primary breakout direction (LONG or SHORT). A meta-model accepts or rejects; it NEVER
   inverts or alters direction.
2. Zero Fictitious Friction: Rejected candidates emit None, consuming $0.00 collateral
   and paying $0.00 execution fees.
3. Pre-Declared Hypotheses: Policies H1 through H4 are frozen hypotheses, not tuned parameters:
   - H1: tau=0.50, cooldown=0 bars
   - H2: tau=0.50, cooldown=4 bars
   - H3: tau=0.55, cooldown=0 bars
   - H4: tau=0.55, cooldown=4 bars
4. Full Auditability: Every rejected candidate is logged with timestamp, symbol, direction,
   confidence score, and rejection reason.
5. Exit Signal Passthrough: Midline exits and barrier exits generated by the primary strategy
   or portfolio engine are never suppressed.
"""

from typing import List, Dict, Any, Optional, Tuple, Union
from enum import Enum
from dataclasses import dataclass, field
import numpy as np

from backend.backtest.engine import BaseStrategy
from backend.backtest.events import BarEvent, SignalEvent
from backend.backtest.schemas import PositionSide
from backend.backtest.position import PositionTracker
from backend.ml.meta_models import BaseMetaModel


